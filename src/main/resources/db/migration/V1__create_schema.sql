CREATE TABLE pizzas (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      VARCHAR(255)  NOT NULL UNIQUE,
    price     NUMERIC(8, 2) NOT NULL,
    available BOOLEAN       NOT NULL
);

CREATE TABLE orders (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tracking_code  VARCHAR(255)                NOT NULL UNIQUE,
    status         VARCHAR(255)                NOT NULL CHECK (status IN ('CREATED', 'IN_PROGRESS', 'COMPLETED', 'CANCELED')),
    priority_score INTEGER                     NOT NULL,
    started_at     TIMESTAMP(6) WITH TIME ZONE,
    completed_at   TIMESTAMP(6) WITH TIME ZONE,
    canceled_at    TIMESTAMP(6) WITH TIME ZONE,
    created_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_status_created_at ON orders (status, created_at);
CREATE INDEX idx_status_priority_created ON orders (status, priority_score, created_at);

CREATE TABLE order_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   BIGINT        NOT NULL REFERENCES orders (id),
    pizza_id   BIGINT        NOT NULL REFERENCES pizzas (id),
    quantity   INTEGER       NOT NULL,
    notes      VARCHAR(255),
    unit_price NUMERIC(8, 2) NOT NULL
);

CREATE INDEX idx_order_items_order_id ON order_items (order_id);
